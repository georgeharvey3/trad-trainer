import type { LibraryTune } from "../src/lib/types.ts";

/** A Library row as the ingest builds it: Session fields plus the ABC of the first setting. */
export type IngestTune = Omit<LibraryTune, "id"> & { abc: string };

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * SQL that upserts the tunes into `public.library`. A second run does not
 * make duplicates: it refreshes only `tunebooks` of each existing row.
 */
export function buildLibrarySql(tunes: IngestTune[]): string {
  const rows = tunes.map(
    (t) =>
      `  (${Math.trunc(t.sessionId)}, ${quote(t.name)}, ${quote(t.type)}, ${quote(t.key)}, ${Math.trunc(t.tunebooks)}, ${quote(t.abc)})`,
  );
  return [
    "-- Generated by scripts/ingest-library.ts. Do not edit by hand.",
    "-- Run in the Supabase SQL editor.",
    "insert into public.library (session_id, name, type, key, tunebooks, abc) values",
    rows.join(",\n"),
    "on conflict (session_id) do update set tunebooks = excluded.tunebooks;",
    "",
  ].join("\n");
}
